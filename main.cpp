/**
 * @file main.cpp
 * @brief Демонстрация класса Polynomial (лабораторная №3).
 *
 * Программа демонстрирует все возможности класса Polynomial:
 *  - три конструктора (по умолчанию, параметризованный, копирования);
 *  - унарные операции ++ и -- (префиксные и постфиксные);
 *  - операции присваивания +=, -=, *=, /=;
 *  - бинарные операции +, -, *, /;
 *  - операции сравнения <, >, <=, >=, ==, !=;
 *  - вычисление значения в точке evaluate(x);
 *  - поиск корней findRoots() со статическим счётчиком вызовов.
 *
 * @note В конце каждого раздела выводятся пояснения, что именно
 *       демонстрируется — чтобы на защите было видно, что все
 *       требования лабораторной выполнены.
 */

#include "Polynomial.h"
#include <iostream>

/**
 * @brief Точка входа. Демонстрирует все перегрузки класса Polynomial.
 *
 * Программа разбита на 7 логических секций, соответствующих
 * требованиям лабораторной работы:
 *  1. Создание объектов тремя разными конструкторами.
 *  2. Унарные операции (++ и --, префиксные и постфиксные).
 *  3. Операции присваивания (+=, -=, *=, /=).
 *  4. Бинарные операции (+, -, *, /) — реализованы через присваивание.
 *  5. Операции сравнения (<, >, <=, >=, ==, !=).
 *  6. Вычисление значения полинома в точке.
 *  7. Поиск корней и статический счётчик вызовов.
 *
 * @return 0 при успешном завершении программы.
 */
int main()
{
    // ============================================================
    // СЕКЦИЯ 1. ТРИ СПОСОБА СОЗДАНИЯ ОБЪЕКТА
    // ============================================================
    std::cout << "===== 1. ТРИ СПОСОБА СОЗДАНИЯ =====\n";

    /// @brief p1 — создан конструктором по умолчанию.
    Polynomial p1;

    /// @brief p2 — создан параметризованным конструктором.
    Polynomial p2(1, -3, 2);

    /// @brief p3 — создан конструктором копирования (копия p2).
    Polynomial p3(p2);

    std::cout << "\np1 = "; p1.print();
    std::cout << "p2 = "; p2.print();
    std::cout << "p3 = "; p3.print();

    // ============================================================
    // СЕКЦИЯ 2. УНАРНЫЕ ОПЕРАЦИИ
    // ============================================================
    std::cout << "\n===== 2. УНАРНЫЕ ОПЕРАЦИИ =====\n";

    Polynomial p = p2;
    std::cout << "Исходный p = "; p.print();

    /// @brief Префиксный ++: сначала увеличивает, потом возвращает.
    std::cout << "++p = "; (++p).print();

    /// @brief Постфиксный ++: возвращает копию ДО увеличения.
    std::cout << "p++ (возврат): "; (p++).print();
    std::cout << "После p++: "; p.print();

    /// @brief Префиксный --: сначала уменьшает, потом возвращает.
    std::cout << "--p = "; (--p).print();

    /// @brief Постфиксный --: возвращает копию ДО уменьшения.
    std::cout << "p-- (возврат): "; (p--).print();
    std::cout << "После p--: "; p.print();

    // ============================================================
    // СЕКЦИЯ 3. ОПЕРАЦИИ ПРИСВАИВАНИЯ
    // ============================================================
    std::cout << "\n===== 3. ОПЕРАЦИИ ПРИСВАИВАНИЯ =====\n";

    Polynomial q(1, 2, 3);
    Polynomial r(4, 5, 6);

    std::cout << "q = "; q.print();
    std::cout << "r = "; r.print();

    /// @brief += поэлементно складывает коэффициенты.
    q += r;  std::cout << "q += r -> "; q.print();

    /// @brief -= поэлементно вычитает коэффициенты.
    q -= r;  std::cout << "q -= r -> "; q.print();

    /// @brief *= умножает все коэффициенты на число.
    q *= 2;  std::cout << "q *= 2 -> "; q.print();

    /// @brief /= делит все коэффициенты на число.
    q /= 2;  std::cout << "q /= 2 -> "; q.print();

    // ============================================================
    // СЕКЦИЯ 4. БИНАРНЫЕ ОПЕРАЦИИ (реализованы через присваивание)
    // ============================================================
    std::cout << "\n===== 4. БИНАРНЫЕ ОПЕРАЦИИ =====\n";

    Polynomial a(1, 1, 1), b(2, 2, 2);
    std::cout << "a = "; a.print();
    std::cout << "b = "; b.print();

    /// @brief operator+ реализован через operator+=.
    std::cout << "a + b = "; (a + b).print();

    /// @brief operator- реализован через operator-=.
    std::cout << "a - b = "; (a - b).print();

    /// @brief operator* реализован через operator*=.
    std::cout << "a * 3 = "; (a * 3).print();

    /// @brief operator/ реализован через operator/=.
    std::cout << "b / 2 = "; (b / 2).print();

    // ============================================================
    // СЕКЦИЯ 5. ОПЕРАЦИИ СРАВНЕНИЯ
    // ============================================================
    std::cout << "\n===== 5. ОПЕРАЦИИ СРАВНЕНИЯ (по значению при x = 0) =====\n";

    Polynomial m(1, 2, 3);
    Polynomial n(4, 5, 6);
    std::cout << "m = "; m.print();
    std::cout << "n = "; n.print();

    std::cout << "m <  n : " << (m <  n) << "\n";
    std::cout << "m >  n : " << (m >  n) << "\n";
    std::cout << "m <= n : " << (m <= n) << "\n";
    std::cout << "m >= n : " << (m >= n) << "\n";
    std::cout << "m == n : " << (m == n) << "\n";
    std::cout << "m != n : " << (m != n) << "\n";

    // ============================================================
    // СЕКЦИЯ 6. ВЫЧИСЛЕНИЕ ЗНАЧЕНИЯ В ТОЧКЕ
    // ============================================================
    std::cout << "\n===== 6. ВЫЧИСЛЕНИЕ ЗНАЧЕНИЯ =====\n";

    Polynomial f(1, -3, 2);
    std::cout << "f(x) = 1x^2 - 3x + 2\n";
    std::cout << "f(0) = " << f.evaluate(0) << "\n";
    std::cout << "f(1) = " << f.evaluate(1) << "\n";
    std::cout << "f(2) = " << f.evaluate(2) << "\n";

    // ============================================================
    // СЕКЦИЯ 7. ПОИСК КОРНЕЙ И СТАТИЧЕСКИЙ СЧЁТЧИК
    // ============================================================
    std::cout << "\n===== 7. ПОИСК КОРНЕЙ =====\n";

    /// @brief Корни: x² - 3x + 2 = 0 → x₁ = 1, x₂ = 2.
    f.findRoots();
    std::cout << "Вызовов findRoots: " << Polynomial::getRootsCallCount() << "\n";

    /// @brief Корни: x² - 4 = 0 → x₁ = -2, x₂ = 2.
    Polynomial g(1, 0, -4);
    g.findRoots();

    /// @brief Дискриминант < 0 → нет действительных корней.
    Polynomial h(1, 2, 5);
    h.findRoots();

    /// @brief Линейный случай (a = 0): 2x - 4 = 0 → x = 2.
    Polynomial lin(0, 2, -4);
    lin.findRoots();

    std::cout << "\nВсего вызовов findRoots: "
              << Polynomial::getRootsCallCount() << "\n";

    std::cout << "\n===== ЗАВЕРШЕНИЕ =====\n";
    return 0;
}
